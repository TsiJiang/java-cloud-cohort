public class Ex02 {
    public static void main(String[] args) {
        //Declaration
        String firstName;       // (your first name)
        String city;            // (the city where you live)
        int yearsOfExperience;  // (a whole number)
        double hoursPerWeek;    // (a number with a decimal point)
        boolean isEnrolled;     // (true or false)
        char firstInitial;      // (a single letter in single quotes, e.g., 'M')
        //Assignment
        firstName = "Xavier";
        city = "Seattle";
        yearsOfExperience = 0;
        hoursPerWeek = 18.0;
        isEnrolled = true;
        firstInitial = 'X';
        //Printing
        System.out.println("First Name: " + firstName + "\n");
        System.out.println("City: " + city + "\n");
        System.out.println("Years of Experience: " + yearsOfExperience +"\n");
        System.out.println("Hours per Week: " + hoursPerWeek + "\n");
        System.out.println("Enrolled: " + isEnrolled + "\n");
        System.out.println("First Initial: " + firstInitial + "\n");
    }
}